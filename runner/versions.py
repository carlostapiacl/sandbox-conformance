#!/usr/bin/env python3
"""Which version of each sandbox changed which result.

  versions.py [run-dir-parent ...] > results/versions.md

Reads every <sandbox>.json of the runs judged by the spec (those that record
spec_version) under the given folders (default: results/), keeps the latest run
of each sandbox version (a run's baseline/ re-measure included), and compares
consecutive versions contract by contract.
A contract is compared only when both records have the same contract_sha256:
a result that changed because the contract changed is not a change of version.
The runs themselves explain what their runner changed (each run's README).
"""
import glob, json, os, re, sys

ORDER = ["sandbox-runtime", "nono", "codex", "landrun", "tartaros"]
COUNTED = ["contained", "escaped", "control-broke", "unsupported", "vacuous", "inconclusive"]


def vkey(v):
    """Sort key for versions such as 0.0.81, 0.163.0, 0.1.0-alpha.6."""
    main, _, pre = v.partition("-")
    nums = [int(x) if x.isdigit() else 0 for x in main.split(".")]
    tail = [int(x) if x.isdigit() else x for x in pre.replace("-", ".").split(".")] if pre else []
    return (nums, 0 if pre else 1, [str(t).zfill(8) for t in tail])


def load(parents):
    runs = {}  # sandbox -> version -> (run, data)
    for parent in parents:
        # A run's baseline/ holds the previous version re-measured on the same
        # runner and contracts; it counts as the latest run of that version.
        files = glob.glob(os.path.join(parent, "*", "*.json")) + \
            glob.glob(os.path.join(parent, "*", "baseline", "*.full.json"))
        for f in sorted(files):
            try:
                d = json.load(open(f))
            except ValueError:
                continue
            if not isinstance(d, dict) or not d.get("spec_version") or "contracts" not in d:
                continue
            run = os.path.relpath(os.path.dirname(f), parent).replace(os.sep, "/")
            # Some sandboxes print more than the number ("tartaros 0.1.0-alpha.6 (linux/...)").
            m = re.search(r"\d+\.\d+[0-9A-Za-z.\-]*", d["version"])
            v = m.group(0) if m else d["version"]
            prev = runs.setdefault(d["sandbox"], {}).get(v)
            if prev is None or run > prev[0]:
                runs[d["sandbox"]][v] = (run, d)
    return runs


def main(parents):
    runs = load(parents)
    out = ["# Versions: what changed, and in which version", "",
           "Generated by `runner/versions.py` from the runs judged by "
           "[`spec/verdicts.md`](../spec/verdicts.md). For each sandbox, the latest run of each "
           "version, then every contract whose result changed from one measured version to the next. "
           "A contract is compared only if its file is byte-identical in both runs "
           "(`contract_sha256`), so a change listed here comes from the sandbox, not from the lab. "
           "Counts are not a ranking (spec §8).", ""]
    names = [n for n in ORDER if n in runs] + sorted(n for n in runs if n not in ORDER)
    for name in names:
        vers = sorted(runs[name], key=vkey)
        out += [f"## {name}", "", "| version | run | " + " | ".join(COUNTED) + " |",
                "|---|---|" + "---|" * len(COUNTED)]
        for v in vers:
            run, d = runs[name][v]
            cnt = {k: sum(1 for c in d["contracts"] if c["result"] == k) for k in COUNTED}
            link = run.split("/")[0]
            label = run.replace("/baseline", ", baseline")
            out.append(f"| {v} | [{label}]({link}/README.md) | " + " | ".join(str(cnt[k]) for k in COUNTED) + " |")
        out.append("")
        if len(vers) == 1:
            out += ["Only one version measured.", ""]
        for a, b in zip(vers, vers[1:]):
            (ra, da), (rb, db) = runs[name][a], runs[name][b]
            ca = {c["id"]: c for c in da["contracts"]}
            cb = {c["id"]: c for c in db["contracts"]}
            same = [i for i in ca if i in cb and ca[i].get("contract_sha256") == cb[i].get("contract_sha256")]
            changed = sorted((i for i in same if ca[i]["result"] != cb[i]["result"]),
                             key=lambda i: (cb[i]["result"] != "contained", i))
            skipped = len(set(ca) | set(cb)) - len(same)
            out += [f"### {a} → {b}", ""]
            if changed:
                out += ["| contract | severity | " + a + " | " + b + " |", "|---|---|---|---|"]
                out += [f"| `{i}` | {cb[i].get('severity', '')} | {ca[i]['result']} | **{cb[i]['result']}** |"
                        for i in changed]
            else:
                out.append("No result changed.")
            out.append("")
            out.append(f"{len(same)} contracts compared" +
                       (f"; {skipped} not compared (the contract changed or is in only one run)." if skipped else "."))
            out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1:] or [os.path.join(os.path.dirname(__file__), "..", "results")])
